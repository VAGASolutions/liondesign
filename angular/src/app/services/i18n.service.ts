@Injectable({ providedIn: 'root' })
export class I18nService {
  lang = signal<Lang>('en');
  t = computed(() => TRANSLATIONS[this.lang()]);

  constructor() {
    const saved = (localStorage.getItem('lang') as Lang) || 'en';
    this.lang.set(saved);
  }

  toggle() {
    this.lang.update(l => l === 'en' ? 'hu' : 'en');
    localStorage.setItem('lang', this.lang());
  }
}
